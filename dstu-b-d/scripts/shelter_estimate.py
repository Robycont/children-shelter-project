def load_norm_index() -> dict[str, dict]:
    """Індекс норм. Ключ — повний шифр з маркою (ЕД/М/Р), напр. 'ЕД17-1-1'.

    Голий шифр ('17-1-1') теж підтримується і вказує на Д.2.2 (пріоритет),
    бо шифри збірників повторюються між комплексами.
    """
    idx: dict[str, dict] = {}
    for komplek in ("d2.2", "d2.3", "d2.4"):
        for path in (ZB / komplek).glob("*.json"):
            z = json.loads(path.read_text(encoding="utf-8"))
            for g in z["grupy"]:
                for n in g["normy"]:
                    rec = {
                        **n,
                        "kompleks": z["kompleks"],
                        "zbirnyk": z["nomer"],
                        "nazva_zbirnyka": z["nazva"],
                        "dstu": z.get("dstu"),
                        "marka": z.get("marka"),
                        "shifr_povnyy": f"{z.get('marka','')}{n['shifr']}",
                    }
                    idx[rec["shifr_povnyy"]] = rec
                    # голий шифр — пріоритет Д.2.2 (перший записаний)
                    idx.setdefault(n["shifr"], rec)
    return idx


def build_estimate() -> dict:
    idx = load_norm_index()
    rows = []
    missing = []
    total = 0.0
    for i, (shifr, qty, comment) in enumerate(POSITIONS, start=1):
        n = idx.get(shifr)
        if not n:
            missing.append(shifr)
            continue
        pid = (n.get("resursy") or {}).get("pidsumky") or {}
        unit_cost = pid.get("priami_vytraty_uah") or 0
        cost = round(unit_cost * qty, 2)
        total += cost
        rows.append({
            "npp": i,
            "shifr": shifr,
            "nazva": n["nazva"],
            "komentar_obsyagu": comment,
            "odynytsya": n["odynytsya"],
            "kilkist": qty,
            "tsina_za_od_uah": unit_cost,
            "suma_uah": cost,
            "trud_lyud_god": ((n.get("resursy") or {}).get("trud_robitnykiv") or {}).get("lyud_god"),
            "trud_vsogo_lyud_god": round((((n.get("resursy") or {}).get("trud_robitnykiv") or {}).get("lyud_god") or 0) * qty, 2),
            "dstu": n.get("dstu"),
            "zbirnyk": n.get("nazva_zbirnyka"),
        })

    estimate = {
        "obyekt": "Дитячий притулок (орієнтовний локальний кошторис)",
        "prymitky": [
            "Обсяги — укрупнений шаблон для 2-поверхової будівлі; замінити на дані робочого проекту.",
            "Ціни — орієнтовні прямі витрати з каталогу ресурсів; додати загальновиробничі, прибуток, ПДВ, індекси.",
            "Відсутні шифри (якщо є) потрібно додати до збірників або замінити аналогами.",
        ],
        "vidsutni_shyfry": missing,
        "pozytsiyi": rows,
        "pidsumky": {
            "kilkist_pozytsiy": len(rows),
            "priami_vytraty_uah": round(total, 2),
            "zagalnovyrobnychi_20pct_uah": round(total * 0.20, 2),
            "admin_3pct_uah": round(total * 0.03, 2),
            "prybutok_5pct_uah": round(total * 0.05, 2),
            "razom_bez_pdv_uah": round(total * 1.28, 2),
            "pdv_20pct_uah": round(total * 1.28 * 0.20, 2),
            "vsego_z_pdv_uah": round(total * 1.28 * 1.20, 2),
            "trud_robitnykiv_lyud_god": round(sum(r["trud_vsogo_lyud_god"] or 0 for r in rows), 1),
        },
    }
    return estimate


def main() -> None:
    EXPORTS.mkdir(parents=True, exist_ok=True)
    est = build_estimate()
    (EXPORTS / "lokalnyy-koshtorys-prytulok.json").write_text(
        json.dumps(est, ensure_ascii=False, indent=2) + "\n", encoding="utf-8"
    )
    fields = [
        "npp", "shifr", "nazva", "komentar_obsyagu", "odynytsya", "kilkist",
        "tsina_za_od_uah", "suma_uah", "trud_lyud_god", "trud_vsogo_lyud_god", "zbirnyk", "dstu",
    ]
    with (EXPORTS / "lokalnyy-koshtorys-prytulok.csv").open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        for r in est["pozytsiyi"]:
            w.writerow({k: r.get(k) for k in fields})
    print(json.dumps(est["pidsumky"], ensure_ascii=False, indent=2))
    if est["vidsutni_shyfry"]:
        print("MISSING:", est["vidsutni_shyfry"])


if __name__ == "__main__":
    main()
