def empty_resursy() -> dict:
    return {
        "trud_lyud_god": None,
        "mashynisty_lyud_god": None,
        "mashyny": [],
        "materialy": [],
    }


def apply_extra(zbirnyk: dict, kompleks: str) -> dict:
    nomer = zbirnyk["nomer"]
    relevant = [e for e in EXTRA if e[0] == kompleks and e[1] == nomer]
    if not relevant:
        return zbirnyk

    groups_by_no = {g["grupa"]: g for g in zbirnyk["grupy"]}
    for _, _, gi, gname, items in relevant:
        if gi not in groups_by_no:
            groups_by_no[gi] = {
                "grupa": gi,
                "nazva": gname,
                "odynytsya": items[0][1] if items else "",
                "sklad_robit": [],
                "normy": [],
            }
        g = groups_by_no[gi]
        g["nazva"] = gname
        existing = {n["nazva"] for n in g["normy"]}
        for nazva, unit in items:
            if nazva in existing:
                continue
            ni = len(g["normy"]) + 1
            g["normy"].append({
                "shifr": f"{nomer}-{gi}-{ni}",
                "nazva": nazva,
                "odynytsya": unit,
                "sklad_robit": [],
                "prymitka": "",
                "resursy": empty_resursy(),
            })
            existing.add(nazva)
        # перенумерувати шифри
        for i, n in enumerate(g["normy"], start=1):
            n["shifr"] = f"{nomer}-{gi}-{i}"

    zbirnyk["grupy"] = [groups_by_no[k] for k in sorted(groups_by_no)]
    return zbirnyk
