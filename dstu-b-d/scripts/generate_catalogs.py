def export_csv(all_norms: list[dict], path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fields = ["kompleks", "zbirnyk", "nazva_zbirnyka", "dstu", "grupa", "nazva_grupy", "shifr", "nazva_normy", "odynytsya", "priorytet_prytulok"]
    with path.open("w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=fields)
        w.writeheader()
        for row in all_norms:
            w.writerow(row)


def flatten_norms(z: dict) -> list[dict]:
    rows = []
    for g in z["grupy"]:
        for n in g["normy"]:
            rows.append({
                "kompleks": z["kompleks"],
                "zbirnyk": z["nomer"],
                "nazva_zbirnyka": z["nazva"],
                "dstu": z["dstu"],
                "grupa": g["grupa"],
                "nazva_grupy": g["nazva"],
                "shifr": n["shifr"],
                "nazva_normy": n["nazva"],
                "odynytsya": n["odynytsya"],
                "priorytet_prytulok": z["priorytet_prytulok"],
            })
    return rows


