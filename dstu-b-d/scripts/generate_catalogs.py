def dump_json(path: Path, data: object) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(data, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )


def norm(code: str, name: str, unit: str, sklad: list[str] | None = None, note: str = "") -> dict:
    return {
        "shifr": code,
        "nazva": name,
        "odynytsya": unit,
        "sklad_robit": sklad or [],
        "prymitka": note,
        "resursy": {
            "trud_lyud_god": None,
            "mashynisty_lyud_god": None,
            "mashyny": [],
            "materialy": [],
        },
    }


def group(number: int, name: str, unit: str, normy: list[dict], sklad: list[str] | None = None) -> dict:
    return {
        "grupa": number,
        "nazva": name,
        "odynytsya": unit,
        "sklad_robit": sklad or [],
        "normy": normy,
    }


def zbirnyk(
    complex_code: str,
    number: int,
    name: str,
    dstu: str,
    marka: str,
    groups: list[dict],
    priority: bool = False,
    notes: list[str] | None = None,
) -> dict:
    return {
        "kompleks": complex_code,
        "nomer": number,
        "nazva": name,
        "dstu": dstu,
        "marka": marka,
        "priorytet_prytulok": priority,
        "prymitky": notes
        or [
            "Каталог робіт сформовано за структурою РЕКН ДСТУ Б Д.",
            "Кількісні показники ресурсів (труд, машини, матеріали) заповнюються з офіційного НДІ / КНУ.",
            "Шифр норми: збірник-група-норма (наприклад 8-5-1).",
        ],
        "grupy": groups,
    }


