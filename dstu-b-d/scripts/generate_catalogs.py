def _groups_from_specs(zbirnyk_no: int, specs: list[tuple]) -> list[dict]:
    groups = []
    for gi, (gname, unit, items) in enumerate(specs, start=1):
        normy = [
            norm(f"{zbirnyk_no}-{gi}-{ni}", item, unit)
            for ni, item in enumerate(items, start=1)
        ]
        groups.append(group(gi, gname, unit, normy))
    return groups


